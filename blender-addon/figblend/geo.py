"""Rebuild imported UI elements as Geometry Nodes meshes.

Imported shapes are curves or single quads: right for a sharp, flat UI, wrong
for deforming it. A Wave or Simple Deform modifier moves vertices, and a quad
has four. This swaps a chosen element for a dense mesh generated by a node
group -- by default the user's "Button Custom" -- sized, rounded, coloured and
textured to match, with the element's own text and icon carried onto it.

The node group is looked up by name in the open file, or appended from a
library .blend set in the add-on preferences. Inputs are matched by name, so
any group with the same interface (Height, Roundness, Text, Font, ...) works,
and inputs a group does not have are simply skipped.

Nothing is deleted. The originals are hidden and remembered on the new object,
so Flat puts them back.
"""

import math

import bpy
from mathutils import Matrix, Vector

from . import builder

DEFAULT_GROUP = "Button Custom"

# How a replaced element and its rebuild find each other again.
SOURCES_KEY = "figblend_geo_sources"   # on the geo object: names it replaced
ROOT_KEY = "figblend_geo_root"         # on the geo object: the shape it rebuilt
GEO_KEY = "figblend_geo"               # on the geo object: marker


# --- node group --------------------------------------------------------------

def node_group(name, library=""):
    """The geometry node group to build with, appending it if necessary.

    Raises ValueError with a message meant for the user.
    """
    group = bpy.data.node_groups.get(name)
    if group is not None and group.bl_idname == "GeometryNodeTree":
        return group

    path = bpy.path.abspath(library) if library else ""
    if not path:
        raise ValueError(
            "No node group named '%s' in this file. Append it, or set a library "
            ".blend in FigBlend's add-on preferences." % name)
    try:
        with bpy.data.libraries.load(path, link=False) as (src, dst):
            if name not in src.node_groups:
                raise ValueError("'%s' has no node group named '%s'." % (path, name))
            dst.node_groups = [name]
    except OSError as err:
        raise ValueError("Could not open library '%s': %s" % (path, err))

    group = dst.node_groups[0] if dst.node_groups else None
    if group is None or group.bl_idname != "GeometryNodeTree":
        raise ValueError("'%s' in '%s' is not a geometry node group." % (name, path))
    return group


def _input_items(group):
    return {item.name: item for item in group.interface.items_tree
            if item.item_type == "SOCKET" and item.in_out == "INPUT"}


def set_input(modifier, items, name, value):
    """Set a modifier input by its interface name. False if the group lacks it.

    Blender 5 moved modifier inputs from ID properties (modifier["Socket_3"])
    to modifier.properties.inputs.Socket_3.value; both are handled.
    """
    item = items.get(name)
    if item is None:
        return False
    props = getattr(modifier, "properties", None)
    inputs = getattr(props, "inputs", None) if props is not None else None
    if inputs is not None:
        slot = getattr(inputs, item.identifier)
        current = slot.value
        # Vector sockets may be 2D or 3D depending on the group; match length.
        if hasattr(current, "__len__") and not isinstance(current, str):
            value = tuple(value)[:len(current)] + (0.0,) * (len(current) - len(value))
        slot.value = value
    else:
        modifier[item.identifier] = value
    return True


# --- measuring ---------------------------------------------------------------

def _local_points(root):
    """Evaluated vertices of a shape and its SVG parts, in the root's space."""
    depsgraph = bpy.context.evaluated_depsgraph_get()
    to_root = root.matrix_world.inverted()
    points, faces = [], []
    for target in builder.thickness_targets(root):
        evaluated = target.evaluated_get(depsgraph)
        try:
            mesh = evaluated.to_mesh()
        except RuntimeError:
            continue
        if mesh is None:
            continue
        into = to_root @ target.matrix_world
        coords = [into @ v.co for v in mesh.vertices]
        points.extend(coords)
        faces.append([(p.normal.copy(), p.area, [coords[i] for i in p.vertices])
                      for p in mesh.polygons])
        evaluated.to_mesh_clear()
    return points, faces


def measure(root):
    """Footprint, depth and corner radius of an element, in its own space."""
    points, face_sets = _local_points(root)
    if not points:
        return None
    xs = [p.x for p in points]
    ys = [p.y for p in points]
    zs = [p.z for p in points]
    width, height = max(xs) - min(xs), max(ys) - min(ys)
    front = max(zs)

    # A rounded rectangle has area w*h - (4 - pi) r^2, so the radius falls out
    # of the front-face area. The largest single path stands for the shape: an
    # outlined border overlaps its fill, and summing them would double-count.
    area = 0.0
    for faces in face_sets:
        part = sum(a for n, a, verts in faces
                   if abs(n.z) > 0.9 and sum(v.z for v in verts) / len(verts) > front - 1e-5)
        area = max(area, part)
    radius = math.sqrt(max(0.0, (width * height - area) / (4.0 - math.pi))) if area else 0.0

    return {
        "width": width, "height": height,
        "center": Vector(((max(xs) + min(xs)) / 2.0, (max(ys) + min(ys)) / 2.0)),
        "back": min(zs), "front": front,
        "radius": min(radius, min(width, height) / 2.0),
    }


def _world_box(obj):
    """World-space centre and size of an object's evaluated geometry."""
    depsgraph = bpy.context.evaluated_depsgraph_get()
    xs, ys = [], []
    for target in builder.thickness_targets(obj):
        evaluated = target.evaluated_get(depsgraph)
        try:
            mesh = evaluated.to_mesh()
        except RuntimeError:
            continue
        if mesh is None:
            continue
        for v in mesh.vertices:
            w = target.matrix_world @ v.co
            xs.append(w.x)
            ys.append(w.y)
        evaluated.to_mesh_clear()
    if not xs:
        return None, None
    return (Vector(((max(xs) + min(xs)) / 2.0, (max(ys) + min(ys)) / 2.0, 0.0)),
            Vector((max(xs) - min(xs), max(ys) - min(ys), 0.0)))


# --- what goes onto the button -----------------------------------------------

def _children(obj):
    return [c for c in obj.children if not c.get("figblend_part")]


def split_content(root):
    """(text, icon, rest): the parts a button carries, and everything else.

    Only a button-shaped element hands its contents over: at most one text and
    at most one icon, nothing else. A card with a heading, body copy and three
    buttons keeps its children as they are and only its own shape is rebuilt.
    """
    children = _children(root)
    texts = [c for c in children if c.type == "FONT"]
    icons = [c for c in children if c.type in {"CURVE", "MESH"} and not _children(c)]
    rest = [c for c in children if c not in texts and c not in icons]
    if rest or len(texts) > 1 or len(icons) > 1 or not (texts or icons):
        return None, None, children
    return (texts[0] if texts else None), (icons[0] if icons else None), []


def _first_material(obj):
    for slot in obj.material_slots:
        if slot.material:
            return slot.material
    return None


def _font_of(text_obj):
    font = text_obj.data.font
    if font is None:
        font = bpy.data.fonts.load("<builtin>", check_existing=True)
    return font


# --- building ----------------------------------------------------------------

def make(root, group, height=0.0, carry_content=True, density=32):
    """Replace `root` with a node-group mesh. Returns the new object.

    `density` is the number of segments across the element's shorter side.
    The group's Resolution is per metre, and a UI element is a fraction of a
    metre, so a fixed Resolution leaves a small chip with too few vertices to
    deform. Deriving it per element keeps every rebuild equally wavy.
    """
    frame = measure(root)
    if frame is None or frame["width"] <= 0.0 or frame["height"] <= 0.0:
        raise ValueError("'%s' has no surface to rebuild." % root.name)

    text, icon, keep = split_content(root) if carry_content else (None, None, _children(root))

    # Thickness: what Build 3D already gave it, else a slab proportional to the
    # element, so a small chip and a large card both read as solid.
    depth = height or root.get("figblend_depth", 0.0) or 0.08 * min(frame["width"], frame["height"])

    # A flat quad at the back of the element: the group grows upwards from it,
    # so the rebuilt object occupies the same depth the element did.
    w2, h2 = frame["width"] / 2.0, frame["height"] / 2.0
    cx, cy, z = frame["center"].x, frame["center"].y, frame["back"]
    mesh = bpy.data.meshes.new(root.name + " Geo")
    mesh.from_pydata([(cx - w2, cy - h2, z), (cx + w2, cy - h2, z),
                      (cx + w2, cy + h2, z), (cx - w2, cy + h2, z)], [], [(0, 1, 2, 3)])
    uv = mesh.uv_layers.new(name="UVMap")
    for i, co in enumerate([(0, 0), (1, 0), (1, 1), (0, 1)]):
        uv.data[i].uv = co

    obj = bpy.data.objects.new(root.name + " Geo", mesh)
    for collection in root.users_collection:
        collection.objects.link(obj)
    obj.parent = root.parent
    obj.matrix_parent_inverse = root.matrix_parent_inverse.copy()
    obj.matrix_basis = root.matrix_basis.copy()

    # Slots in the group's default order: body, text, cursor, icon.
    body = _first_material(root)
    text_mat = _first_material(text) if text else body
    icon_mat = _first_material(icon) if icon else body
    for mat in (body, text_mat, text_mat, icon_mat):
        mesh.materials.append(mat)

    modifier = obj.modifiers.new("FigBlend Geo", "NODES")
    modifier.node_group = group
    items = _input_items(group)
    put = lambda name, value: set_input(modifier, items, name, value)

    half_short = min(frame["width"], frame["height"]) / 2.0
    resolution_item = items.get("Resolution")
    if resolution_item is not None:
        limit = getattr(resolution_item, "max_value", 200.0)
        put("Resolution", float(min(limit, max(1.0, density / (2.0 * half_short)))))
    put("Height", depth)
    # Text and icon relief are absolute lengths in the group, tuned for its own
    # default Height. At UI scale they would tower over the button, so keep the
    # group author's proportions instead of their absolute values.
    default_height = getattr(items.get("Height"), "default_value", 0.0)
    if default_height:
        for name in ("Text Depth", "Text Bevel", "Icon Depth", "Icon Bevel"):
            item = items.get(name)
            if item is not None:
                put(name, depth * item.default_value / default_height)
    put("Roundness", min(1.0, frame["radius"] / half_short) if half_short else 0.0)
    put("Button Slot", 1)
    put("Text Slot", 2)
    put("Cursor Slot", 3)
    put("Icon Slot", 4)

    put("Show Text", False)
    if text is not None:
        apply_text(obj, modifier, items, text)

    put("Show Icon", False)
    icon_depth = None
    if icon is not None:
        icon_depth = _prepare_icon(icon)
        apply_icon(obj, modifier, items, icon)

    # Children the button does not absorb stay where they are, now hanging off
    # the rebuild so moving it still moves them.
    for child in keep:
        world = child.matrix_world.copy()
        child.parent = obj
        child.matrix_world = world

    # Inputs set through modifier.properties do not notify the depsgraph, so
    # without this the object keeps its first evaluation: no text, no icon.
    obj.update_tag()
    _lift_relief(obj, modifier, items, {
        "Text Depth": text.get("figblend_depth") if text is not None else None,
        "Icon Depth": icon_depth,
    })
    if icon is not None:
        _settle_icon(obj, icon, icon_depth)

    replaced = [root] + [o for o in (text, icon) if o is not None]
    for original in replaced:
        original["figblend_geo_hidden_render"] = original.hide_render
        _hide(original, True)

    obj[GEO_KEY] = True
    obj[ROOT_KEY] = root.name
    obj[SOURCES_KEY] = [o.name for o in replaced]
    obj["figblend_z_index"] = root.get("figblend_z_index", 0)
    return obj


def find_modifier(obj):
    """The geometry nodes modifier on `obj` whose group has a text section."""
    for modifier in getattr(obj, "modifiers", []):
        if (modifier.type == "NODES" and modifier.node_group is not None
                and "Text" in _input_items(modifier.node_group)):
            return modifier
    return None


def get_input(modifier, items, name, fallback=None):
    item = items.get(name)
    if item is None:
        return fallback
    props = getattr(modifier, "properties", None)
    inputs = getattr(props, "inputs", None) if props is not None else None
    if inputs is not None:
        return getattr(inputs, item.identifier).value
    return modifier.get(item.identifier, getattr(item, "default_value", fallback))


def _plane(obj):
    """Centre (x, y) and z of the flat input mesh the group grows from."""
    verts = obj.data.vertices if obj.type == "MESH" else []
    if not len(verts):
        return 0.0, 0.0, 0.0
    xs = [v.co.x for v in verts]
    ys = [v.co.y for v in verts]
    return (max(xs) + min(xs)) / 2.0, (max(ys) + min(ys)) / 2.0, min(v.co.z for v in verts)


def _proportional(items, name, height):
    """A relief value in the group author's proportion to the button height."""
    item, height_item = items.get(name), items.get("Height")
    default_height = getattr(height_item, "default_value", 0.0)
    if item is None or not default_height:
        return None
    return height * item.default_value / default_height


def apply_text(obj, modifier, items, text):
    """Put a Blender text object onto the group's text section.

    Size is the text's own: FigBlend already sized it to Figma's, and the
    group draws text through the same font machinery, so the number carries
    over unchanged. Position is the text's centre relative to the button's,
    which holds whatever its alignment. Colour goes into the text slot.
    """
    put = lambda name, value: set_input(modifier, items, name, value)
    put("Show Text", True)
    put("Text", text.data.body)
    put("Font", _font_of(text))
    put("Text Size", text.data.size * text.matrix_world.to_scale().x)
    # Only when the group exposes them; "Button Custom" does not.
    put("Character Spacing", text.data.space_character)
    put("Line Spacing", text.data.space_line)

    bpy.context.view_layer.update()
    cx, cy, z = _plane(obj)
    centre, _size = _world_box(text)
    if centre is not None:
        local = obj.matrix_world.inverted() @ centre
        put("Text Offset", (local.x - cx, local.y - cy))

    material = _first_material(text)
    slot = int(get_input(modifier, items, "Text Slot", 2) or 2)
    if material is not None:
        while len(obj.material_slots) < slot:
            obj.data.materials.append(material)
        obj.material_slots[slot - 1].material = material
    obj["figblend_geo_text"] = text.name


ICON_COLLECTION_KEY = "figblend_geo_icon_collection"


def apply_icon(obj, modifier, items, icon):
    """Put a shape onto the group's icon section.

    A single-path shape goes in as the Icon Object. One that FigBlend imported
    as several paths (a fill plus an outlined stroke, say) goes in as an Icon
    Collection, or only its first path would show. That collection is not
    linked to the scene; the group still reads it, hidden paths included.
    """
    put = lambda name, value: set_input(modifier, items, name, value)
    _release_icon_collection(obj)

    parts = builder.thickness_targets(icon)
    if len(parts) > 1 and "Icon Collection" in items:
        holder = bpy.data.collections.new("%s Icon" % icon.name)
        for part in parts:
            holder.objects.link(part)
        put("Icon Object", None)
        put("Icon Collection", holder)
        obj[ICON_COLLECTION_KEY] = holder.name
    else:
        put("Icon Collection", None)
        put("Icon Object", icon)

    put("Show Icon", True)
    bpy.context.view_layer.update()
    cx, cy, _z = _plane(obj)
    centre, size = _world_box(icon)
    if centre is not None:
        # The group fits the icon so its longest side equals Icon Size.
        put("Icon Size", max(size.x, size.y))
        local = obj.matrix_world.inverted() @ centre
        put("Icon Position", (local.x - cx, local.y - cy))

    material = _first_material(icon)
    slot = int(get_input(modifier, items, "Icon Slot", 4) or 4)
    if material is not None:
        while len(obj.material_slots) < slot:
            obj.data.materials.append(material)
        obj.material_slots[slot - 1].material = material
    obj["figblend_geo_icon"] = icon.name


HELD_DEPTH_KEY = "figblend_geo_depth"


def _prepare_icon(icon):
    """Hand the group a flat icon, remembering the thickness it had.

    The group extrudes flat paths by Icon Depth, but a shape that already has
    Build 3D reaches it as a solid mesh, which it can only use as-is -- seated
    half a millimetre into the body, so it shows thinner than it was. Flat
    paths get extruded by the full amount instead. Meshes cannot be, so those
    are corrected after the fact in _settle_icon.
    """
    # Already merged once: the remembered thickness is the real one.
    depth = icon.get(HELD_DEPTH_KEY) or icon.get("figblend_depth")
    if not depth:
        return None
    icon[HELD_DEPTH_KEY] = depth
    if icon.type in builder.CURVE_TYPES:
        builder.clear_thickness(icon)
    return depth


def _settle_icon(obj, icon, depth):
    """Make a mesh icon stand `depth` proud of the face, as it did before.

    A mesh reaches the group with its own thickness, sunk into the body. Grow
    that thickness by however much is hidden, measured on the result.
    """
    if not depth or icon.type != "MESH":
        return
    modifier = find_modifier(obj)
    items = _input_items(modifier.node_group)
    slot = int(get_input(modifier, items, "Icon Slot", 4) or 4) - 1
    height = get_input(modifier, items, "Height", 0.0) or 0.0
    top = _plane(obj)[2] + height
    bpy.context.view_layer.update()
    evaluated = obj.evaluated_get(bpy.context.evaluated_depsgraph_get())
    mesh = evaluated.to_mesh()
    try:
        zs = [mesh.vertices[i].co.z for p in mesh.polygons if p.material_index == slot
              for i in p.vertices]
    finally:
        evaluated.to_mesh_clear()
    if not zs:
        return
    shortfall = depth - (max(zs) - top)
    if abs(shortfall) > 1e-7:
        builder.apply_thickness(icon, icon.get("figblend_depth", depth) + shortfall)
        obj.update_tag()


def _give_back(original):
    """Undo what merging did to an object: show it, restore its thickness."""
    _hide(original, False)
    held = original.get(HELD_DEPTH_KEY)
    if held:
        builder.apply_thickness(original, held)
        del original[HELD_DEPTH_KEY]


def _release_icon_collection(obj):
    holder = bpy.data.collections.get(obj.get(ICON_COLLECTION_KEY, ""))
    if holder is not None:
        bpy.data.collections.remove(holder)  # its objects keep their own collections
    obj.pop(ICON_COLLECTION_KEY, None)


def _lift_relief(obj, modifier, items, reliefs):
    """Make text and icon stand proud of the button face by a set amount.

    `reliefs` maps "Text Depth" / "Icon Depth" to how far each should rise
    above the face, or None for the group author's proportion of the height.

    A group can seat its relief into the body by a fixed distance so it never
    floats -- "Button Custom" uses half a millimetre. Fine on a 30 cm button;
    at UI scale that is deeper than the whole relief, so the label ends up
    buried. Measure how far each one sinks below the top face and add it on.
    """
    pairs = {"Text Depth": ("Text Slot", "Text Bevel", 2),
             "Icon Depth": ("Icon Slot", "Icon Bevel", 4)}
    height = get_input(modifier, items, "Height", 0.0) or 0.0
    _cx, _cy, base = _plane(obj)
    top = base + height

    bpy.context.view_layer.update()
    evaluated = obj.evaluated_get(bpy.context.evaluated_depsgraph_get())
    mesh = evaluated.to_mesh()
    try:
        lowest = {}
        for poly in mesh.polygons:
            for vi in poly.vertices:
                z = mesh.vertices[vi].co.z
                if z < lowest.get(poly.material_index, float("inf")):
                    lowest[poly.material_index] = z
    finally:
        evaluated.to_mesh_clear()

    changed = False
    for depth_name, (slot_name, bevel_name, default_slot) in pairs.items():
        if depth_name not in reliefs or items.get(depth_name) is None:
            continue
        index = int(get_input(modifier, items, slot_name, default_slot) or default_slot) - 1
        if index not in lowest:
            continue  # nothing of this kind on the button
        relief = reliefs[depth_name]
        if not relief:
            relief = _proportional(items, depth_name, height)
        if not relief:
            continue
        sink = max(0.0, top - lowest[index])
        set_input(modifier, items, depth_name, relief + sink)
        # Keep the bevel inside the relief, in the group's own ratio.
        depth_item, bevel_item = items.get(depth_name), items.get(bevel_name)
        if bevel_item is not None and depth_item.default_value:
            set_input(modifier, items, bevel_name,
                      relief * bevel_item.default_value / depth_item.default_value)
        changed = True
    if changed:
        obj.update_tag()


def merge(obj, text=None, icon=None):
    """Move a separate text and/or icon onto an existing Geo Mesh.

    Size and position come from each object as it is; thickness from its
    Build 3D depth if it has one. The button shows one text and one icon, so
    whatever held that place before is given back. Flat restores these too.
    """
    modifier = find_modifier(obj)
    if modifier is None:
        raise ValueError("'%s' has no geometry node group with a text section. "
                         "Make it a Geo Mesh first." % obj.name)
    items = _input_items(modifier.node_group)
    if icon is not None and "Show Icon" not in items:
        raise ValueError("'%s' has no icon section." % modifier.node_group.name)

    sources = list(obj.get(SOURCES_KEY, []))

    def swap(key, incoming):
        previous = bpy.data.objects.get(obj.get(key, ""))
        if previous is not None and previous is not incoming and previous.name in sources:
            _give_back(previous)
            sources.remove(previous.name)

    reliefs = {}
    if text is not None:
        swap("figblend_geo_text", text)
        apply_text(obj, modifier, items, text)
        reliefs["Text Depth"] = text.get("figblend_depth")
    if icon is not None:
        swap("figblend_geo_icon", icon)
        icon_depth = _prepare_icon(icon)
        apply_icon(obj, modifier, items, icon)
        reliefs["Icon Depth"] = icon_depth

    obj.update_tag()
    _lift_relief(obj, modifier, items, reliefs)
    if icon is not None:
        _settle_icon(obj, icon, reliefs.get("Icon Depth"))

    for incoming in (text, icon):
        if incoming is not None and incoming.name not in sources:
            incoming["figblend_geo_hidden_render"] = incoming.hide_render
            _hide(incoming, True)
            sources.append(incoming.name)
    obj[SOURCES_KEY] = sources
    return modifier


def _hide(obj, hidden):
    # The source of an Object Info node still evaluates when hidden this way,
    # which is what lets a hidden icon keep feeding the button.
    obj.hide_set(hidden)
    if hidden:
        obj.hide_render = True
    else:
        obj.hide_render = bool(obj.get("figblend_geo_hidden_render", False))
        obj.pop("figblend_geo_hidden_render", None)
    for part in obj.children:
        if part.get("figblend_part"):
            part.hide_set(hidden)
            part.hide_render = obj.hide_render


def restore(obj):
    """Undo make(): bring the originals back and remove the rebuild."""
    if not obj.get(GEO_KEY):
        return False
    root = bpy.data.objects.get(obj.get(ROOT_KEY, ""))
    for name in obj.get(SOURCES_KEY, []):
        original = bpy.data.objects.get(name)
        if original is not None:
            _give_back(original)
    for child in [c for c in obj.children]:
        world = child.matrix_world.copy()
        child.parent = root
        child.matrix_world = world
    _release_icon_collection(obj)
    mesh = obj.data
    bpy.data.objects.remove(obj)
    if mesh is not None and mesh.users == 0:
        bpy.data.meshes.remove(mesh)
    return True
